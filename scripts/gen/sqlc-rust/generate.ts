#!/usr/bin/env node
import { readFileSync } from "node:fs";

import { z } from "zod";

const column = z.object({
  name: z.string(),
  original_name: z.string(),
  table: z.object({ name: z.string(), schema: z.string(), catalog: z.string() }).nullable(),
  type: z.object({ name: z.string() }),
  not_null: z.boolean(),
  is_array: z.literal(false),
  is_sqlc_slice: z.literal(false),
  embed_table: z.null(),
});
const query = z.object({
  name: z.string().regex(/^[A-Z][a-zA-Z0-9]*$/u),
  cmd: z.enum([":one", ":many", ":exec", ":execrows"]),
  text: z.string().min(1),
  columns: z.array(column).nullable(),
  params: z.array(z.object({ number: z.number().int().positive(), column })).nullable(),
});
const request = z.object({ settings: z.object({ engine: z.literal("sqlite") }), queries: z.array(query), plugin_options: z.string() });
type Column = z.infer<typeof column>;

const sqliteTypes = new Map([
  ["INTEGER", "i64"],
  ["TEXT", "String"],
  ["REAL", "f64"],
  ["BLOB", "Vec<u8>"],
]);

function rustName(name: string, queryName: string): string {
  if (!/^[a-z][a-z0-9_]*$/u.test(name) || ["self", "super", "crate"].includes(name)) {
    throw new Error(`${queryName}: expected a snake_case Rust identifier, got ${name}`);
  }
  return `r#${name}`;
}

function fields(columns: Column[], name: string): string[] {
  const seen = new Set<string>();
  return columns.map((c) => {
    if (seen.has(c.name)) throw new Error(`${name}: repeated column or parameter ${c.name}; use a SQL alias or named parameter`);
    seen.add(c.name);
    const type = sqliteTypes.get(c.type.name.toUpperCase());
    if (!type) throw new Error(`${name}.${c.name}: unsupported SQLite type ${c.type.name}`);
    return `    pub ${rustName(c.name, name)}: ${c.not_null ? type : `Option<${type}>`},`;
  });
}

function sqlLiteral(sql: string): string {
  let hashes = "#";
  while (sql.includes(`"${hashes}`)) hashes += "#";
  return `r${hashes}"${sql}"${hashes}`;
}

function render(q: z.infer<typeof query>, names: Set<string>, rows?: Map<string, string>): string {
  const fn = q.name
    .replace(/([A-Z]+)([A-Z][a-z])/gu, "$1_$2")
    .replace(/([a-z0-9])([A-Z])/gu, "$1_$2")
    .toLowerCase();
  const functionName = rustName(fn, q.name);
  if (names.has(functionName)) throw new Error(`${q.name}: duplicate generated function ${fn}`);
  names.add(functionName);
  const params = (q.params ?? []).toSorted((a, b) => a.number - b.number);
  const columns = q.columns ?? [];
  const returnsRows = q.cmd === ":one" || q.cmd === ":many";
  if (returnsRows !== columns.length > 0) throw new Error(`${q.name}: result columns disagree with ${q.cmd}`);
  if (params.some((p, i) => p.number !== i + 1)) throw new Error(`${q.name}: expected contiguous bind positions`);

  const args = `${q.name}Params`;
  const row = `${q.name}Row`;
  const lines: string[] = [];
  if (params.length > 0) {
    lines.push(
      `pub struct ${args} {`,
      ...fields(
        params.map((p) => p.column),
        q.name,
      ),
      "}",
      "",
    );
  }
  if (returnsRows) {
    const record = fields(columns, q.name);
    const key = JSON.stringify(columns.map((c) => [c.table, c.original_name, c.name, c.type, c.not_null]));
    const shared = columns.every((c) => c.table?.name) ? rows?.get(key) : undefined;
    if (shared) {
      lines.push(`pub type ${row} = ${shared};`, "");
    } else {
      rows?.set(key, row);
      lines.push("#[derive(sqlx::FromRow)]", `pub struct ${row} {`, ...record, "}", "");
    }
  }
  const result = { ":one": row, ":many": `Vec<${row}>`, ":exec": "()", ":execrows": "u64" }[q.cmd];
  const call = returnsRows ? `sqlx::query_as::<_, ${row}>` : "sqlx::query";
  lines.push(`pub async fn ${functionName}<'e>(`, "    db: impl sqlx::SqliteExecutor<'e>,");
  if (params.length > 0) lines.push(`    params: ${args},`);
  lines.push(`) -> Result<${result}, sqlx::Error> {`, `    ${call}(${sqlLiteral(q.text)})`);
  for (const p of params) lines.push(`        .bind(params.r#${p.column.name})`);
  const finish = {
    ":one": ".fetch_one(db).await",
    ":many": ".fetch_all(db).await",
    ":exec": ".execute(db).await.map(|_| ())",
    ":execrows": ".execute(db).await.map(|r| r.rows_affected())",
  }[q.cmd];
  lines.push(`        ${finish}`, "}");
  return lines.join("\n");
}

const input = request.parse(JSON.parse(readFileSync(0, "utf8")));
const names = new Set<string>();
const options = z
  .object({
    share_table_rows: z.boolean().optional(),
    file: z
      .string()
      .regex(/^[a-z][a-z0-9_]*\.rs$/u)
      .optional(),
  })
  .parse(input.plugin_options ? JSON.parse(Buffer.from(input.plugin_options, "base64").toString("utf8")) : {});
const rows = options.share_table_rows === true ? new Map<string, string>() : undefined;
const source = ["// Generated by sqlc-rust. Do not edit.", ...input.queries.map((q) => render(q, names, rows))].join("\n\n") + "\n";
process.stdout.write(JSON.stringify({ files: [{ name: options.file ?? "queries.rs", contents: Buffer.from(source).toString("base64") }] }));

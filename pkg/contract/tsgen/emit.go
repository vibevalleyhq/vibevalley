package tsgen

import (
	"bytes"
	"fmt"
	"slices"
	"strings"
)

const (
	oxfmtPrintWidth = 160
	generatedHeader = "// Generated by cmd/vibe-tsgen from pkg/contract/*.go; do not edit: vpx scripts/gen/go-contract.ts --write."
)

// GeneratedFiles holds the deterministically emitted TypeScript contract artifacts.
type GeneratedFiles struct {
	ShapesTS []byte
	SchemaTS []byte
}

// Emit produces formatted TypeScript shapes.ts and Zod v4 schema.ts from a parsed Package.
func Emit(pkg *Package) (GeneratedFiles, error) {
	if pkg == nil {
		return GeneratedFiles{}, fmt.Errorf("cannot emit nil package")
	}
	brands := collectUsedBrands(pkg)
	shapes := emitShapes(pkg, brands)
	schema := emitSchema(pkg, brands)
	return GeneratedFiles{
		ShapesTS: shapes,
		SchemaTS: schema,
	}, nil
}

func collectUsedBrands(pkg *Package) []string {
	set := make(map[string]struct{})
	var walk func(TypeExpr)
	walk = func(expr TypeExpr) {
		switch t := expr.(type) {
		case BrandedIDType:
			set[t.Name] = struct{}{}
		case ArrayType:
			walk(t.Elem)
		case NullableType:
			walk(t.Elem)
		case MapType:
			walk(t.Key)
			walk(t.Val)
		case InlineStructType:
			for _, f := range t.Fields {
				walk(f.Type)
			}
		}
	}
	for _, d := range pkg.Decls {
		switch d.Kind {
		case DeclAlias:
			walk(d.AliasType)
		case DeclStruct:
			for _, f := range d.Fields {
				walk(f.Type)
			}
		}
	}
	out := make([]string, 0, len(set))
	for name := range set {
		out = append(out, name)
	}
	slices.Sort(out)
	return out
}

func emitShapes(pkg *Package, brands []string) []byte {
	var buf bytes.Buffer
	buf.WriteString(generatedHeader)
	buf.WriteByte('\n')

	if len(brands) > 0 {
		buf.WriteByte('\n')
		emitNamedImport(&buf, "import type", brands, "../common/shapes")
	}

	for _, d := range pkg.Decls {
		buf.WriteByte('\n')
		switch d.Kind {
		case DeclEnum:
			emitEnumShape(&buf, d)
		case DeclAlias:
			fmt.Fprintf(&buf, "export type %s = %s;\n", d.Name, formatTSType(d.AliasType, 0))
		case DeclStruct:
			emitStructInterface(&buf, d)
		}
	}

	return buf.Bytes()
}

func emitNamedImport(buf *bytes.Buffer, prefix string, names []string, from string) {
	single := fmt.Sprintf("%s { %s } from %q;", prefix, strings.Join(names, ", "), from)
	if len(single) <= oxfmtPrintWidth {
		buf.WriteString(single)
		buf.WriteByte('\n')
		return
	}
	fmt.Fprintf(buf, "%s {\n", prefix)
	for _, name := range names {
		fmt.Fprintf(buf, "  %s,\n", name)
	}
	fmt.Fprintf(buf, "} from %q;\n", from)
}

func emitEnumShape(buf *bytes.Buffer, d Decl) {
	quoted := make([]string, len(d.EnumValues))
	for i, v := range d.EnumValues {
		quoted[i] = quoteTSString(v)
	}

	arrSingle := fmt.Sprintf("export const %sValues = [%s] as const;", d.Name, strings.Join(quoted, ", "))
	if len(arrSingle) <= oxfmtPrintWidth {
		buf.WriteString(arrSingle)
		buf.WriteByte('\n')
	} else {
		fmt.Fprintf(buf, "export const %sValues = [\n", d.Name)
		for _, q := range quoted {
			fmt.Fprintf(buf, "  %s,\n", q)
		}
		buf.WriteString("] as const;\n")
	}

	fmt.Fprintf(buf, "export type %s = (typeof %sValues)[number];\n", d.Name, d.Name)
}

func emitStructInterface(buf *bytes.Buffer, d Decl) {
	if len(d.Fields) == 0 {
		fmt.Fprintf(buf, "export interface %s {}\n", d.Name)
		return
	}
	fmt.Fprintf(buf, "export interface %s {\n", d.Name)
	for _, f := range d.Fields {
		emitInterfaceField(buf, f, 1)
	}
	buf.WriteString("}\n")
}

func emitInterfaceField(buf *bytes.Buffer, f Field, indent int) {
	pad := strings.Repeat("  ", indent)
	opt := ""
	if f.Optional {
		opt = "?"
	}
	typeStr := formatTSType(f.Type, indent)
	if f.Nullable {
		typeStr += " | null"
	}
	fmt.Fprintf(buf, "%s%s%s: %s;\n", pad, formatPropKey(f.JSONName), opt, typeStr)
}

func formatTSType(expr TypeExpr, indent int) string {
	switch t := expr.(type) {
	case PrimitiveType:
		switch t.Kind {
		case PrimString:
			return "string"
		case PrimInt, PrimFloat:
			return "number"
		case PrimBool:
			return "boolean"
		case PrimUnknown:
			return "unknown"
		}
	case BrandedIDType:
		return t.Name
	case NamedType:
		return t.Name
	case NullableType:
		return formatTSType(t.Elem, indent) + " | null"
	case ArrayType:
		elemStr := formatTSType(t.Elem, indent)
		if _, isNullable := t.Elem.(NullableType); isNullable {
			return "(" + elemStr + ")[]"
		}
		return elemStr + "[]"
	case MapType:
		keyStr := formatMapKeyTSType(t.Key)
		valStr := formatTSType(t.Val, indent)
		return fmt.Sprintf("Record<%s, %s>", keyStr, valStr)
	case InlineStructType:
		if len(t.Fields) == 0 {
			return "{}"
		}
		var b bytes.Buffer
		b.WriteString("{\n")
		for _, f := range t.Fields {
			emitInterfaceField(&b, f, indent+1)
		}
		b.WriteString(strings.Repeat("  ", indent))
		b.WriteByte('}')
		return b.String()
	}
	return "unknown"
}

func formatMapKeyTSType(expr TypeExpr) string {
	switch t := expr.(type) {
	case PrimitiveType:
		return "string"
	case NamedType:
		return t.Name
	default:
		return "string"
	}
}

func emitSchema(pkg *Package, brands []string) []byte {
	hasEnum := false
	for _, d := range pkg.Decls {
		if d.Kind == DeclEnum {
			hasEnum = true
			break
		}
	}

	var buf bytes.Buffer
	buf.WriteString(generatedHeader)
	buf.WriteString("\n\n")
	buf.WriteString(`import { z } from "zod";`)
	buf.WriteString("\n\n")
	buf.WriteString(`import type { Codec } from "../codec";`)
	buf.WriteByte('\n')
	if len(brands) > 0 {
		emitNamedImport(&buf, "import", brands, "../common/schema")
	}
	if hasEnum {
		buf.WriteString(`import * as T from "./shapes";`)
	} else {
		buf.WriteString(`import type * as T from "./shapes";`)
	}
	buf.WriteByte('\n')

	for _, d := range pkg.Decls {
		buf.WriteByte('\n')
		switch d.Kind {
		case DeclEnum:
			fmt.Fprintf(&buf, "export const %s = z.enum(T.%sValues) satisfies Codec<T.%s>;\n", d.Name, d.Name, d.Name)
		case DeclAlias:
			fmt.Fprintf(&buf, "export const %s = %s satisfies Codec<T.%s>;\n", d.Name, formatZodType(d.AliasType, 0), d.Name)
		case DeclStruct:
			emitStructSchema(&buf, d)
		}
	}

	return buf.Bytes()
}

func emitStructSchema(buf *bytes.Buffer, d Decl) {
	if len(d.Fields) == 0 {
		fmt.Fprintf(buf, "export const %s = z.object({}) satisfies Codec<T.%s>;\n", d.Name, d.Name)
		return
	}
	fmt.Fprintf(buf, "export const %s = z.object({\n", d.Name)
	for _, f := range d.Fields {
		emitSchemaField(buf, f, 1)
	}
	fmt.Fprintf(buf, "}) satisfies Codec<T.%s>;\n", d.Name)
}

func emitSchemaField(buf *bytes.Buffer, f Field, indent int) {
	pad := strings.Repeat("  ", indent)
	zodStr := formatZodType(f.Type, indent)
	if f.Optional {
		zodStr = fmt.Sprintf("z.exactOptional(%s)", zodStr)
	} else if f.Nullable {
		zodStr = fmt.Sprintf("z.nullable(%s)", zodStr)
	}
	fmt.Fprintf(buf, "%s%s: %s,\n", pad, formatPropKey(f.JSONName), zodStr)
}

func formatZodType(expr TypeExpr, indent int) string {
	switch t := expr.(type) {
	case PrimitiveType:
		switch t.Kind {
		case PrimString:
			return "z.string()"
		case PrimInt:
			return "z.number().int()"
		case PrimFloat:
			return "z.number()"
		case PrimBool:
			return "z.boolean()"
		case PrimUnknown:
			return "z.unknown()"
		}
	case BrandedIDType:
		return t.Name
	case NamedType:
		return t.Name
	case NullableType:
		return fmt.Sprintf("z.nullable(%s)", formatZodType(t.Elem, indent))
	case ArrayType:
		return fmt.Sprintf("z.array(%s)", formatZodType(t.Elem, indent))
	case MapType:
		keyZod := formatMapKeyZodType(t.Key)
		return fmt.Sprintf("z.record(%s, %s)", keyZod, formatZodType(t.Val, indent))
	case InlineStructType:
		if len(t.Fields) == 0 {
			return "z.object({})"
		}
		var b bytes.Buffer
		b.WriteString("z.object({\n")
		for _, f := range t.Fields {
			emitSchemaField(&b, f, indent+1)
		}
		b.WriteString(strings.Repeat("  ", indent))
		b.WriteString("})")
		return b.String()
	}
	return "z.unknown()"
}

func formatMapKeyZodType(expr TypeExpr) string {
	switch t := expr.(type) {
	case PrimitiveType:
		return "z.string()"
	case NamedType:
		return t.Name
	default:
		return "z.string()"
	}
}

func formatPropKey(name string) string {
	if isJSIdentifier(name) {
		return name
	}
	return quoteTSString(name)
}

func isJSIdentifier(s string) bool {
	if s == "" {
		return false
	}
	for i := 0; i < len(s); i++ {
		c := s[i]
		isAlpha := (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || c == '_' || c == '$'
		isDigit := c >= '0' && c <= '9'
		if i == 0 {
			if !isAlpha {
				return false
			}
		} else if !isAlpha && !isDigit {
			return false
		}
	}
	return true
}

func quoteTSString(s string) string {
	var b strings.Builder
	b.Grow(len(s) + 2)
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch c {
		case '"':
			b.WriteString(`\"`)
		case '\\':
			b.WriteString(`\\`)
		case '\b':
			b.WriteString(`\b`)
		case '\f':
			b.WriteString(`\f`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		default:
			if c < 0x20 || c == 0x7f {
				fmt.Fprintf(&b, `\u%04x`, c)
			} else {
				b.WriteByte(c)
			}
		}
	}
	b.WriteByte('"')
	return b.String()
}

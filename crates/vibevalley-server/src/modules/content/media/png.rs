//! Generated PNG validation, ported from media/png.ts (CRC, size, filters).
use std::io::Read;
pub fn valid(bytes: &[u8], width: i64, height: i64) -> bool {
    if bytes.len() < 45 || !bytes.starts_with(b"\x89PNG\r\n\x1a\n") || width <= 0 || height <= 0 {
        return false;
    }
    let number = |n: usize| u32::from_be_bytes(bytes[n..n + 4].try_into().unwrap()) as usize;
    let mut compressed = Vec::new();
    let mut stride = 0;
    let mut ended = false;
    let mut at = 8;
    while at < bytes.len() {
        if at + 12 > bytes.len() {
            return false;
        }
        let length = number(at);
        let Some(end) = at.checked_add(12 + length) else {
            return false;
        };
        if end > bytes.len() {
            return false;
        }
        let kind = &bytes[at + 4..at + 8];
        if crc32fast::hash(&bytes[at + 4..end - 4]) as usize != number(end - 4) {
            return false;
        }
        if at == 8 {
            if kind != b"IHDR" || length != 13 || number(at + 8) != width as usize || number(at + 12) != height as usize {
                return false;
            }
            let depth = bytes[at + 16] as usize;
            let color = bytes[at + 17];
            let channels = match color {
                0 | 3 => 1,
                2 => 3,
                4 => 2,
                6 => 4,
                _ => return false,
            };
            if ![1, 2, 4, 8, 16].contains(&depth)
                || ([2, 4, 6].contains(&color) && depth < 8)
                || (color == 3 && depth > 8)
                || bytes[at + 18..at + 21] != [0, 0, 0]
            {
                return false;
            }
            stride = (width as usize * channels * depth).div_ceil(8) + 1;
        } else if kind == b"IHDR" {
            return false;
        }
        if kind == b"IDAT" {
            compressed.extend_from_slice(&bytes[at + 8..end - 4]);
        }
        if kind == b"IEND" {
            if length != 0 || end != bytes.len() {
                return false;
            }
            ended = true;
        }
        at = end;
    }
    let Some(size) = stride.checked_mul(height as usize) else {
        return false;
    };
    if !ended || compressed.is_empty() || size > 32 << 20 {
        return false;
    }
    let mut decoded = Vec::new();
    if flate2::read::ZlibDecoder::new(compressed.as_slice())
        .take(size as u64 + 1)
        .read_to_end(&mut decoded)
        .is_err()
        || decoded.len() != size
    {
        return false;
    }
    decoded.chunks_exact(stride).all(|r| r[0] <= 4)
}

#[cfg(test)]
mod tests {
    use super::valid;
    // Generated by apps/server's media/testdata/png.ts.
    #[test]
    fn original_png_dimensions_crc_and_complete_framing() {
        let bytes = include_bytes!("../../../../tests/fixtures/media.png");
        assert!(valid(bytes, 256, 256));
        assert!(!valid(bytes, 512, 256));
        assert!(!valid(&bytes[..bytes.len() - 1], 256, 256));
        let mut trailing = bytes.to_vec();
        trailing.extend_from_slice(b"trailing");
        assert!(!valid(&trailing, 256, 256));
        let mut corrupt = bytes.to_vec();
        corrupt[50] ^= 1;
        assert!(!valid(&corrupt, 256, 256));
    }
}

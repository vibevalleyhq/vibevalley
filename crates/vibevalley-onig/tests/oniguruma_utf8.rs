/// Explicitly skipped upstream UTF-8 cases (2 of 1547):
/// - L850 `a(?~(?~)).`: nested absent function (?~(?~)): undefined behavior per Oniguruma doc/RE
/// - L1378 `(?:[ab]|(*MAX{2}).)*`: stateful named callout (*MAX{n}): Phase 2 feature
const SKIPPED_COUNT: usize = 2;

#[test]
fn oniguruma_test_utf8_suite() {
    let mut passed = 0usize;
    let mut failed = Vec::new();
    let limits = ExecLimits {
        max_steps: 200_000,
        max_backtrack_stack: 32_768,
        max_call_depth: 64,
    };

    for case in CASES {
        match *case {
            Case::Match { line, pat, hay, from, to, mem } => match OnigRegExp::new(pat) {
                Err(e) => failed.push(format!("L{line} MATCH compile-err /{pat}/: {e}")),
                Ok(re) => match re.with_limits(limits).find(hay) {
                    Err(e) => failed.push(format!("L{line} MATCH exec-err /{pat}/ on {hay:?}: {e}")),
                    Ok(None) => failed.push(format!("L{line} MATCH no-match /{pat}/ on {hay:?} expected ({from},{to})[{mem}]")),
                    Ok(Some(m)) => {
                        let actual = m.get(mem);
                        let expected = if from < 0 { None } else { Some((from as usize, to as usize)) };
                        let got = actual.map(|c| (c.start, c.end));
                        if got == expected {
                            passed += 1;
                        } else {
                            failed.push(format!("L{line} MATCH span /{pat}/ on {hay:?} mem={mem}: expected {expected:?}, got {got:?}"));
                        }
                    }
                },
            },
            Case::NoMatch { line, pat, hay } => match OnigRegExp::new(pat) {
                Err(e) => failed.push(format!("L{line} NOMATCH compile-err /{pat}/: {e}")),
                Ok(re) => match re.with_limits(limits).find(hay) {
                    Err(e) => failed.push(format!("L{line} NOMATCH exec-err /{pat}/ on {hay:?}: {e}")),
                    Ok(None) => passed += 1,
                    Ok(Some(m)) => failed.push(format!("L{line} NOMATCH matched /{pat}/ on {hay:?}: got {:?}", m.full())),
                },
            },
            Case::Error { line, pat, hay, err } => match OnigRegExp::new(pat) {
                Err(_) => passed += 1,
                Ok(re) => match re.with_limits(limits).find(hay) {
                    Err(_) => passed += 1,
                    Ok(m) => failed.push(format!("L{line} ERROR({err}) unexpected-ok /{pat}/ on {hay:?}: {m:?}")),
                },
            },
        }
    }

    assert_eq!(SKIPPED_COUNT, 2);
    assert!(
        failed.is_empty(),
        "{}/{} passed ({SKIPPED_COUNT} skipped), {} failed:
{}",
        passed,
        CASES.len(),
        failed.len(),
        failed.join(
            "
"
        )
    );
    assert_eq!(passed, CASES.len());
}

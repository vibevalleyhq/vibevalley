#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(u8)]
pub enum ErToken {
    End = 0,
    Error = 1,
    ErDiagram = 2,
    Eof = 3,
    Newline = 4,
    Colon = 5,
    StyleSeparator = 6,
    BlockStart = 7,
    BlockStop = 8,
    Sqs = 9,
    Sqe = 10,
    AccTitle = 11,
    AccTitleValue = 12,
    AccDescr = 13,
    AccDescrValue = 14,
    AccDescrMultilineValue = 15,
    EndKw = 16,
    Subgraph = 17,
    DirectionTb = 18,
    DirectionBt = 19,
    DirectionRl = 20,
    DirectionLr = 21,
    ClassDef = 22,
    UnicodeText = 23,
    StyleText = 24,
    Comma = 25,
    Class = 26,
    Style = 27,
    Semi = 28,
    Num = 29,
    Brkt = 30,
    EntityName = 31,
    DecimalNum = 32,
    EntityOne = 33,
    AttributeWord = 34,
    AttributeKey = 35,
    Comment = 36,
    ZeroOrOne = 37,
    ZeroOrMore = 38,
    OneOrMore = 39,
    OnlyOne = 40,
    MdParent = 41,
    NonIdentifying = 42,
    Identifying = 43,
    Word = 44,
    /// A character no rule names; the grammar gives it meaning only as `?` and `,` inside a block.
    Char = 45,
}

impl ErToken {
    pub const fn name(self) -> &'static str {
        match self {
            Self::End => "$end",
            Self::Error => "INVALID",
            Self::ErDiagram => "ER_DIAGRAM",
            Self::Eof => "EOF",
            Self::Newline => "NEWLINE",
            Self::Colon => "COLON",
            Self::StyleSeparator => "STYLE_SEPARATOR",
            Self::BlockStart => "BLOCK_START",
            Self::BlockStop => "BLOCK_STOP",
            Self::Sqs => "SQS",
            Self::Sqe => "SQE",
            Self::AccTitle => "acc_title",
            Self::AccTitleValue => "acc_title_value",
            Self::AccDescr => "acc_descr",
            Self::AccDescrValue => "acc_descr_value",
            Self::AccDescrMultilineValue => "acc_descr_multiline_value",
            Self::EndKw => "END",
            Self::Subgraph => "SUBGRAPH",
            Self::DirectionTb => "direction_tb",
            Self::DirectionBt => "direction_bt",
            Self::DirectionRl => "direction_rl",
            Self::DirectionLr => "direction_lr",
            Self::ClassDef => "CLASSDEF",
            Self::UnicodeText => "UNICODE_TEXT",
            Self::StyleText => "STYLE_TEXT",
            Self::Comma => "COMMA",
            Self::Class => "CLASS",
            Self::Style => "STYLE",
            Self::Semi => "SEMI",
            Self::Num => "NUM",
            Self::Brkt => "BRKT",
            Self::EntityName => "ENTITY_NAME",
            Self::DecimalNum => "DECIMAL_NUM",
            Self::EntityOne => "ENTITY_ONE",
            Self::AttributeWord => "ATTRIBUTE_WORD",
            Self::AttributeKey => "ATTRIBUTE_KEY",
            Self::Comment => "COMMENT",
            Self::ZeroOrOne => "ZERO_OR_ONE",
            Self::ZeroOrMore => "ZERO_OR_MORE",
            Self::OneOrMore => "ONE_OR_MORE",
            Self::OnlyOne => "ONLY_ONE",
            Self::MdParent => "MD_PARENT",
            Self::NonIdentifying => "NON_IDENTIFYING",
            Self::Identifying => "IDENTIFYING",
            Self::Word => "WORD",
            Self::Char => "CHAR",
        }
    }
}

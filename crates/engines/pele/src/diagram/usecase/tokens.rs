/// Mermaid's token types, in an order that makes its token categories ranges:
/// WORD is Usecase..=Identifier, and LABEL_TEXT is Usecase..=LabelSymbol.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(u8)]
pub enum UsecaseToken {
    Eof = 0,
    Usecase = 1,
    Actor = 2,
    SystemBoundary = 3,
    End = 4,
    Direction = 5,
    Td = 6,
    Tb = 7,
    Bt = 8,
    Lr = 9,
    Rl = 10,
    Note = 11,
    For = 12,
    Json = 13,
    ClassDef = 14,
    Class = 15,
    Style = 16,
    Include = 17,
    Extend = 18,
    True = 19,
    False = 20,
    Identifier = 21,
    Number = 22,
    At = 23,
    Comma = 24,
    Colon = 25,
    HashColor = 26,
    CssIdentifier = 27,
    CssEscapedComma = 28,
    Dash = 29,
    Dot = 30,
    Percent = 31,
    CssPunctuation = 32,
    LabelPunctuation = 33,
    LabelSymbol = 34,
    PlainString = 35,
    MarkdownString = 36,
    UnclosedMarkdownString = 37,
    Comment = 38,
    Newline = 39,
    AccDescrBlock = 40,
    AccTitleLine = 41,
    AccDescrLine = 42,
    JsonDeclarationStart = 43,
    JsonObjectLiteral = 44,
    UnclosedJsonObjectLiteral = 45,
    Generalization = 46,
    DependencyArrow = 47,
    StereotypeStart = 48,
    StereotypeEnd = 49,
    StereotypeText = 50,
    UnclosedStereotypeText = 51,
    ClassSeparator = 52,
    ForwardSolid = 53,
    BackwardSolid = 54,
    ForwardCircle = 55,
    BackwardCircle = 56,
    ForwardCross = 57,
    BackwardCross = 58,
    MarkerlessSolid = 59,
    MetadataStart = 60,
    LBrace = 61,
    RBrace = 62,
    LBracket = 63,
    RBracket = 64,
    LParen = 65,
    RParen = 66,
}

